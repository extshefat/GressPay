import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync('src/features/checkout/checkoutMachine.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const flow = await import('data:text/javascript;base64,' + Buffer.from(compiled).toString('base64'));
const method = { code: 'bkash', name: 'bKash', country: 'BD', category: 'mfs', requiresTxidInput: true };
const base = { paymentStatus: 'PENDING', awaitingEvidence: true, availableMethods: [method] };
assert.equal(flow.hasSubmittedPayment(base), false, 'new PENDING checkout cannot skip receiving details');
assert.equal(flow.hasSubmittedPayment({ ...base, awaitingEvidence: false, submittedMethod: 'bkash' }), false);
assert.equal(flow.hasSubmittedPayment({ ...base, submittedMethod: 'bkash', submittedTxid: 'EXAMPLE1234' }), true);
assert.equal(flow.hasSubmittedPayment({ ...base, submittedMethod: 'bkash', verificationMode: 'sms_auto' }), true);
assert.equal(flow.hasSubmittedPayment({ ...base, paymentStatus: 'COMPLETED', submittedMethod: 'bkash' }), false);
const phase = { checkoutStatus: 'PENDING', methodChosen: false, isPollingVerification: false, cancelMessage: null, secondsLeft: 600 };
assert.equal(flow.resolveCheckoutPhase(phase), 'choosing');
assert.equal(flow.resolveCheckoutPhase({ ...phase, isPollingVerification: true }), 'choosing', 'bad legacy waiting flag must not hide unchosen methods');
assert.equal(flow.resolveCheckoutPhase({ ...phase, methodChosen: true, step: 'payer' }), 'payer_details');
assert.equal(flow.resolveCheckoutPhase({ ...phase, methodChosen: true, step: 'payment' }), 'awaiting_payment');
assert.equal(flow.resolveCheckoutPhase({ ...phase, methodChosen: true, isPollingVerification: true }), 'submitted_verifying');
assert.equal(flow.resolveCheckoutPhase({ ...phase, methodChosen: true, isPollingVerification: true, smsAuto: true }), 'waiting_sms');
assert.equal(flow.resolveCheckoutPhase({ ...phase, methodChosen: true, secondsLeft: 0 }), 'confirming_expiry');
assert.equal(flow.resolveCheckoutPhase({ ...phase, checkoutStatus: 'COMPLETED', secondsLeft: 0 }), 'success', 'server confirmation wins over the countdown');
assert.equal(flow.resolveCheckoutPhase({ ...phase, cancelMessage: 'Cancelled' }), 'cancelled');
assert.equal(flow.paymentCategory(method), 'mobile');
assert.equal(flow.paymentCategory({ ...method, country: 'IN', category: 'bank_upi' }), 'india');
assert.equal(flow.paymentCategory({ ...method, country: 'GLOBAL', category: 'crypto' }), 'crypto');
assert.equal(flow.paymentCategory({ ...method, category: 'bank_upi', code: 'future-bank' }), 'bank');
assert.equal(flow.isMobileMethod({ ...method, country: 'PK' }), false, 'regional wallets must not require a Bangladesh phone');
assert.equal(flow.normalizePayerNumber('+880 1712-345678'), '01712345678');
assert.equal(flow.normalizePayerNumber('০১৭১২৩৪৫৬৭৮'), '01712345678');
assert.equal(flow.validPayerNumber('01712345678'), true);
assert.equal(flow.validPayerNumber('01212345678'), false);
assert.equal(flow.validPayerNumber('0171'), false);
assert.equal(flow.validateReference(method, 'EXAMPLE1234'), undefined);
assert.ok(flow.validateReference(method, 'Receipt text with spaces'));
assert.ok(flow.validateReference(method, ''));
assert.equal(flow.validateReference(method, '', true), undefined);
assert.equal(flow.validateReference({ ...method, code: 'usdt_trc20' }, 'a'.repeat(64)), undefined);
assert.ok(flow.validateReference({ ...method, code: 'usdt_trc20' }, 'x'.repeat(64)));
assert.equal(flow.formatSessionClock(601), '10:01');
assert.equal(flow.formatSessionClock(-2), '00:00');
assert.equal(flow.remainingSeconds('2026-11-07T00:01:00Z', Date.parse('2026-11-07T00:00:00Z')), 60);
console.log('PASS checkout progression, genuine-submission resume, server-authoritative outcomes, categories, payer/reference validation and clocks');
